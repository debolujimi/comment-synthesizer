def remove_handle_url_hash_sign(tweet):
    """remove twitter handle and and url from the tweet

    Args:
        tweet (str): raw tweet from the coallated tweets
    Return: 
    
    """
    
    tweet = re.sub(r'https?://[^\s\n\r]+', '', tweet) # remove hyperlink
    tweet = re.sub(r'@[^\s\n\r]+', '', tweet) # remove @ sign of twitter handle tag  
    tweet = re.sub(r'#', '', tweet) # remove hashtag 
    tweet = re.sub(r'[^\w\s]','', tweet) #remove punctuations
    
    return tweet
    
def tokenize_and_stem(tweet):
    """
    Tokenize - meaning convert the sntence into list of word, after which all data will be lowercased, stopword removed 
    and punctuation also removed. For the TOkenization will utiliize Twitter tokenization from NLTK library

    Args:
        tweet (string): returns 
    
    Return 
        (list): A list of cleaned tweet tokeized without stop word and punctuation
    
    """
    
    # Tokenize sentence using the Twitter tokenizer
    tweet_tokenizer = TweetTokenizer(strip_handles=True, preserve_case=False, reduce_len=True)
    tokenized_tweet = tweet_tokenizer.tokenize(tweet)
    
    
    stemmer = PorterStemmer()          # define stemmer type
    wordnet_lemmatizer = WordNetLemmatizer()
    stopwords_english = stopwords.words('english')   # Get list of available stopword  
    
    
    tweets_clean = []

    for word in tokenized_tweet: # Go through every word in your tokens list
        if (word not in stopwords_english and  # remove stopwords
                 word not in string.punctuation):  # remove punctuation
            # stem_word = stemmer.stem(word)        # stem the word; try also lemming of the data.
            lemmatizer_word = wordnet_lemmatizer.lemmatize(word, pos='v')    # lemmatize for verb
            lemmatizer_word = wordnet_lemmatizer.lemmatize(lemmatizer_word, pos='n') # lemmatize for noun
            
            tweets_clean.append(lemmatizer_word)
            
    return tweets_clean

