def Part_of_Speech_Parse(data, row_index, tweet_column):
    sentence = str(data.iloc[row_index][tweet_column])
    sentence_nlp = nlp(sentence)

    # POS tagging with Spacy 
    spacy_pos_tagged = [(word, word.tag_, word.pos_) for word in sentence_nlp]
    df_spacy_tag = pd.DataFrame(spacy_pos_tagged, columns=['Word', 'POS tag', 'Tag type'])

    # POS tagging with nltk
    nltk_pos_tagged = nltk.pos_tag(sentence.split())
    df_nltk_tag = pd.DataFrame(nltk_pos_tagged, columns=['Word', 'POS tag'])

    return df_spacy_tag, df_nltk_tag
